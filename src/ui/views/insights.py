"""Results tab: Insights & hypotheses, each labelled observed / inferred / speculative."""
import streamlit as st

from src.models.run import RunBundle
from src.ui.components import card, label_badge

GROUPS = [("Key findings", {"finding"}), ("Disagreements", {"disagreement"}), ("Emerging trends", {"trend"}),
          ("Hypotheses", {"hypothesis"}), ("Implications & opportunities", {"implication", "opportunity"}),
          ("Risks", {"risk"})]


def render(bundle: RunBundle) -> None:
    st.markdown(label_badge("observed") + " stated directly by sources &nbsp; " + label_badge("inferred") +
                " reasoned from several observations &nbsp; " + label_badge("speculative") + " a hypothesis to test, "
                "not an established fact", unsafe_allow_html=True)

    ref = {r["source_id"]: r["n"] for r in (bundle.report.references if bundle.report else [])}
    claims = {c.id: c for c in bundle.claims}
    if not bundle.insights:
        st.info("No insights were generated. The evidence may have been too thin.", icon=":material/info:")
    counts = {label: sum(i.label.value == label for i in bundle.insights) for label in ("observed", "inferred", "speculative")}
    c = st.columns(3)
    for col, (label, n) in zip(c, counts.items()):
        col.metric(label.title(), n)

    position = 0
    for title, kinds in GROUPS:
        items = [i for i in bundle.insights if i.kind.value in kinds]
        if not items:
            continue
        st.subheader(title)
        for insight in items:
            with card(f"ins-{insight.id}"):
                position += 1
                st.markdown(f'<span class="ds-num">{position:02d}</span>{label_badge(insight.label.value)} '
                            f"**{insight.statement}**", unsafe_allow_html=True)
                if insight.label.value == "speculative":
                    st.caption("Speculative: a plausible hypothesis, not a conclusion supported as fact.")
                st.markdown(f"**Confidence: {insight.confidence}**: {insight.confidence_explanation}")
                st.markdown(f"**Reasoning:** {insight.reasoning}")
                if insight.alternatives:
                    st.markdown("**Alternative explanations:** " + "; ".join(insight.alternatives))
                if insight.limitations:
                    st.markdown("**Limitations:** " + "; ".join(insight.limitations))
                if insight.next_investigation:
                    st.markdown(f"**Next investigation:** {insight.next_investigation}")
                with st.expander(f"Supporting evidence ({len(insight.evidence_claim_ids)})"):
                    for cid in insight.evidence_claim_ids:
                        claim = claims.get(cid)
                        if claim:
                            source = bundle.source(claim.source_id)
                            number = f"[{ref[claim.source_id]}] " if claim.source_id in ref else ""
                            st.markdown(f"> {claim.quote}\n\n{number}{source.title if source else ''} · {claim.location}")
                st.caption(f"Generated by: {insight.generated_by}")
